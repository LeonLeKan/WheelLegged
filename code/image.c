void find_road()
{
    uint8_t istart = road_start;
    uint8_t iend = FAR_LINE;
    //top_road = NEAR_LINE;//赛道最高处所在行数，先初始化话为最低处
    int road_f = -1;//赛道所在连通域父节点编号，先初始化为-1，以判断是否找到赛道
    int while_range_num = 0, roud_while_range_num = 0;
    all_range* twhite_range = NULL;
    road* tmy_road = NULL;
    //寻找赛道所在连通域
    // 寻找最中心的白条子
    for (int i = 1; i <= white_range[istart].num; i++)
        if (white_range[istart].area[i].right - white_range[istart].area[i].left >= 40)
        {

            road_f = find_f(white_range[istart].area[i].connect_num);
            break;
        }

    if (road_f == -1)
    {
        int widthmax = 0, jselect = 1;
        for (int i = 1; i <= white_range[istart].num; i++)
            if (white_range[istart].area[i].right - white_range[istart].area[i].left > widthmax)
            {
                widthmax = white_range[istart].area[i].right - white_range[istart].area[i].left;
                jselect = i;
            }
        road_f = find_f(white_range[istart].area[jselect].connect_num);//找到父节点编号
    }
    //现在我们已经得到了赛道所在连通域父节点编号，接下来把所有父节点编号是road_f的所有白条子扔进赛道数组就行了
    for (int i = istart; i >= iend; i--)
    {
        //变量保存，避免之后写的冗杂且低效
        twhite_range = &white_range[i];
        tmy_road = &my_road[i];
        while_range_num = twhite_range->num;//每行白条数量
        tmy_road->white_num = 0;
        roud_while_range_num = 0;
        for (int j = 1; j <= while_range_num; j++)
        {
            if (find_f(twhite_range->area[j].connect_num) == road_f)
            {
                tmy_road->white_num++; roud_while_range_num++;
                tmy_road->connected[roud_while_range_num].left = twhite_range->area[j].left;
                tmy_road->connected[roud_while_range_num].right = twhite_range->area[j].right;
                tmy_road->connected[roud_while_range_num].width = twhite_range->area[j].right - twhite_range->area[j].left;
            }
        }
    }
}

static bool check_future(uint8_t i_start, uint8_t j_start, uint8_t N)
{
    uint8_t dright, dleft, uright, uleft;
    if (i_start < 5) return true;
    dleft = my_road[i_start].connected[j_start].left;
    dright = my_road[i_start].connected[j_start].right;
    for (uint8_t i = i_start - 1; i > i_start - N; i--)
    {
        bool found_connected = false;
        for (uint8_t j = 1; j <= my_road[i].white_num; j++)
        {
            uleft = my_road[i].connected[j].left;
            uright = my_road[i].connected[j].right;
            if (dleft <= uright && dright >= uleft && uright - uleft > 0.3 * get_expected_road_width(i, 100, 30))
            {
                dleft = uleft;
                dright = uright;
                found_connected = true;
                break;
            }
        }
        if (!found_connected) return false;
    }
    return true;
}


uint8_t find_continue(uint8_t i_start, uint8_t j_start)
{
    uint8_t j_return;
    uint8_t j;
    uint8_t width_max = 0;
    uint8_t width_new = 0;
    uint8_t left = 0;
    uint8_t right = 0;
    uint8_t dright, dleft, uright, uleft;
    j_return = MISS;//如果没找到，输出255
    if (j_start > my_road[i_start].white_num)
        return MISS;
    //选一个重叠最大的
    for (j = 1; j <= my_road[i_start - 1].white_num; j++)
    {
        dleft = my_road[i_start].connected[j_start].left;
        dright = my_road[i_start].connected[j_start].right;
        uleft = my_road[i_start - 1].connected[j].left;
        uright = my_road[i_start - 1].connected[j].right;
        if (//相连
            dleft <= uright
            &&
            dright >= uleft
            )
        {
            //if (i_start >= FAR_LINE + 30 && !check_future(i_start, j_start, 8))
            //    continue;
            //计算重叠大小
            if (dleft < uleft) left = uleft;
            else left = dleft;

            if (dright > uright) right = uright;
            else right = dright;

            width_new = right - left + 1;

            if (width_new > width_max)
            {
                width_max = width_new;
                j_return = j;
            }
        }

    }
    if (j_return == MISS)
    {
        return j_return;
    }
    uint8_t current_line = i_start;
    // 影子干扰情况处理，连接被影子隔断的两个白条
    if (enable_dis_shadow
        && current_line >= NEAR_LINE - 45
        && white_range[current_line].num > 1)
    {
        uint8_t left_dis = 255, right_dis = 255;
        range* left_white = &white_range[current_line].area[j_return - 1];
        range* current_white = &white_range[current_line].area[j_return];
        range* right_white = &white_range[current_line].area[j_return + 1];
        if (j_return > 1)
        {
            left_dis = current_white->left - left_white->right;
        }
        if (j_return < white_range[current_line].num)
        {
            right_dis = right_white->left - current_white->right;
        }
		float max_width = 0;
        switch (now_element)
        {
        case FRONT_STAIRS:
        case BACK_STAIRS:
            max_width = 1.2 * get_expected_road_width(i_start, 140, 20);
            break;
        case SINGLE_SIDE:
            max_width = 1.2 * get_expected_road_width(i_start, 100, 30);
            break;
        default:
            break;
        }
        if (left_dis < right_dis && left_dis < 15 && left_white->left > middle - max_width / 2
            && current_white->right - left_white->left < max_width)
        {
            // 将左边的白条子和当前白条子连接为一个白条
            my_road[current_line].connected[j_return].left = left_white->left;
        }
        else if (right_dis < left_dis && right_dis < 15 && right_white->right < middle + max_width / 2
            && right_white->right - current_white->left < max_width)
        {
            my_road[current_line].connected[j_return].right = right_white->right;
        }
    }

    return j_return;
}


