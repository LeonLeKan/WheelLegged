//利用最小二乘法来算中线斜率来补线
void least_square(uint8_t* line, uint8_t outset, uint8_t limit, float input[])
{
    float k;//最小二乘法算出来的斜率
    float b;//最小二乘法算出来的截距
    uint32_t Sum_xy = 0;//线的xy坐标的乘积之和
    uint32_t Sum_x = 0;//每个点的x的平方之和
    float average_x = 0;//横坐标平均值
    float average_y = 0;//纵坐标平均值
    if (limit < 3)
    {
        input[0] = 0;
        input[1] = line[NEAR_LINE];
    }
    else
    {
        for (int i = outset; i > outset - limit; i--) {
            Sum_xy += i * line[i];
            Sum_x += i * i;
            average_y += (float)line[i];
            average_x += (float)i;
        }
        average_y = average_y / limit;
        average_x = average_x / limit;
        k = (float)(Sum_xy - limit * average_x * average_y) / (Sum_x - limit * average_x * average_x);
        b = average_y - k * average_x;
        input[0] = k;
        input[1] = b;
    }
}

// 带拟合度的最小二乘法来算中线斜率来补线
void least_square_with_R(uint8_t* line, uint8_t outset, uint8_t limit, float input[])
{
    float k = 0.0f; // slope
    float b = 0.0f; // intercept
    float R = 0.0f; // correlation coefficient

    /* use float accumulators to avoid overflow and to compute R correctly */
    float Sum_xy = 0.0f;
    float Sum_xx = 0.0f; /* sum of x^2 */
    float Sum_yy = 0.0f; /* sum of y^2 */
    float average_x = 0.0f;
    float average_y = 0.0f;

    if (limit < 3)
    {
        input[0] = 0.0f;
        /* keep previous behavior: return the value at outset as intercept */
        input[1] = (float)line[outset];
        input[2] = 0.0f;
        return;
    }

    /* safer iteration: iterate exactly `limit` points starting at `outset` and going down */
    int i = (int)outset;
    for (uint8_t cnt = 0; cnt < limit; ++cnt, --i)
    {
        /* guard against negative index just in case */
        if (i < 0) break;
        float x = (float)i;
        float y = (float)line[i];
        Sum_xy += x * y;
        Sum_xx += x * x;
        Sum_yy += y * y;
        average_x += x;
        average_y += y;
    }

    float n = (float)limit;
    average_x /= n;
    average_y /= n;

    float S_xy = Sum_xy - n * average_x * average_y;
    float S_xx = Sum_xx - n * average_x * average_x;
    float S_yy = Sum_yy - n * average_y * average_y;

    /* avoid division by zero and negative sqrt argument */
    if (S_xx == 0.0f)
    {
        k = 0.0f;
        b = average_y;
        R = 0.0f;
    }
    else
    {
        k = S_xy / S_xx;
        b = average_y - k * average_x;
        if (S_xx > 0.0f && S_yy > 0.0f)
        {
            R = S_xy / sqrtf(S_xx * S_yy);
        }
        else
        {
            R = 0.0f;
        }
    }

    input[0] = k;
    input[1] = b;
    input[2] = R;
}


